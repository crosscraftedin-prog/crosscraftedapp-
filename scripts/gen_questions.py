# --- Helper ----------------------------------------------------------------
def q(diff, cat, num, question, options, ans, exp, ref=N, book=N, topic=N):
    """Build a single question dict.
    diff  : difficulty string
    cat   : category string
    num   : question number within group (int)
    options: list of 4 strings
    ans   : correct index (0-3)
    exp   : explanation string
    ref   : scripture reference (or None)
    book  : bible book (or None)
    topic : topic string (or None)

    The options are deterministically shuffled based on the questionId so that
    the correct answer position varies across 0-3, while the output remains
    fully reproducible (same questionId -> same shuffle, every run).
    """
    pts = {"beginners": 10, "intermediate": 20, "skilled": 30, "expert": 50}[diff]
    prefix = {"beginners": "beg", "intermediate": "int",
              "skilled": "skl", "expert": "exp"}
    cat_prefix = {"full_bible": "fb", "new_testament": "nt",
                  "old_testament": "ot", "apologetics": "ap"}
    qid = f"{prefix[diff]}_{cat_prefix[cat]}_{num:03d}"

    # Deterministic shuffle of options based on the questionId.
    # Same id always yields the same ordering -> reproducible JSON output.
    seed = int(hashlib.sha256(qid.encode("utf-8")).hexdigest(), 16) % (2**32)
    rng = random.Random(seed)
    order = list(range(len(options)))
    rng.shuffle(order)
    shuffled_options = [options[i] for i in order]
    new_ans = order.index(ans)  # where the original correct answer landed

    return {
        "questionId": qid,
        "question": question,
        "options": json.dumps(shuffled_options),
        "correctAnswer": new_ans,
        "explanation": exp,
        "scriptureReference": ref,
        "difficulty": diff,
        "category": cat,
        "basePoints": pts,
        "bibleBook": book,
        "topic": topic,
    }


