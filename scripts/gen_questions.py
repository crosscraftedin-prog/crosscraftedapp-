def main():
    # 1. Read existing 100 questions
    with open(INPUT_PATH, "r", encoding="utf-8") as f:
        existing = json.load(f)

    print(f"Loaded {len(existing)} existing questions from part1_beginners.json")

    # 2. Combine existing + new
    all_questions = existing + questions

    # 3. Write all 800 to the output file
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(all_questions, f, indent=2, ensure_ascii=False)

    print(f"Wrote {len(all_questions)} total questions to {OUTPUT_PATH}")

    # 4. Print summary table
    print("\n" + "=" * 70)
    print("QUESTION COUNTS BY DIFFICULTY x CATEGORY")
    print("=" * 70)

    difficulties = ["beginners", "intermediate", "skilled", "expert"]
    categories = ["full_bible", "new_testament", "old_testament", "apologetics"]

    counts = Counter((q["difficulty"], q["category"]) for q in all_questions)

    # Header
    header = f"{'Difficulty':<15}" + "".join(f"{c:<16}" for c in categories) + "Total"
    print(header)
    print("-" * len(header))
    for d in difficulties:
        row = f"{d:<15}"
        total = 0
        for c in categories:
            cnt = counts.get((d, c), 0)
            total += cnt
            row += f"{cnt:<16}"
        row += f"{total}"
        print(row)
    print("-" * len(header))
    # Column totals
    col_row = f"{'TOTAL':<15}"
    grand = 0
    for c in categories:
        cnt = sum(counts.get((d, c), 0) for d in difficulties)
        grand += cnt
        col_row += f"{cnt:<16}"
    col_row += f"{grand}"
    print(col_row)
    print("=" * 70)
    print(f"GRAND TOTAL: {grand} questions")

    # Verify IDs unique and structure valid
    ids = [q["questionId"] for q in all_questions]
    dup_ids = [i for i, n in Counter(ids).items() if n > 1]
    if dup_ids:
        print(f"\nWARNING: Duplicate IDs found: {dup_ids}")
    else:
        print("\nAll question IDs are unique.")

    # Verify each has 4 options and 1 correct answer
    bad = []
    for qd in all_questions:
        opts = json.loads(qd["options"])
        if len(opts) != 4:
            bad.append((qd["questionId"], "wrong option count"))
        if not (0 <= qd["correctAnswer"] <= 3):
            bad.append((qd["questionId"], "bad correctAnswer"))
    if bad:
        print(f"\nWARNING: {len(bad)} malformed questions: {bad[:5]}")
    else:
        print("All questions have exactly 4 options and a valid correctAnswer.")

    # Correct-answer position distribution
    pos_counts = Counter(qd["correctAnswer"] for qd in all_questions)
    print(f"\nCorrect-answer position distribution: {dict(sorted(pos_counts.items()))}")


if __name__ == "__main__":
    main()
